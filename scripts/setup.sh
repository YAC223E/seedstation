#!/usr/bin/env bash
# Prepare SeedStation: Python environment, frontend build, database, admin user,
# isolated qBittorrent profile and runtime directories.
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/common.sh
# shellcheck source=scripts/common.sh
. "$SCRIPT_DIR/common.sh"

WITH_DEV=0
SKIP_FRONTEND=0
START_AFTER=0

usage() {
    cat <<EOF
Usage: ./scripts/setup.sh [options]

Options:
  --dev            Also install backend test dependencies (pytest).
  --skip-frontend  Do not run npm install/build (uses the existing frontend/dist).
  --start          Run ./scripts/start.sh when setup finishes.
  -h, --help       Show this help.
EOF
}

for arg in "$@"; do
    case "$arg" in
        --dev) WITH_DEV=1 ;;
        --skip-frontend) SKIP_FRONTEND=1 ;;
        --start) START_AFTER=1 ;;
        -h|--help) usage; exit 0 ;;
        *) die "Unknown option: $arg (try --help)" ;;
    esac
done

log "SeedStation setup"
log "Project root: $ROOT"

command -v python3 >/dev/null 2>&1 || die "python3 is required."
python3 - <<'PY' || die "Python 3.12 or newer is required."
import sys
raise SystemExit(0 if sys.version_info >= (3, 12) else 1)
PY

if [ "$SKIP_FRONTEND" -eq 0 ]; then
    command -v node >/dev/null 2>&1 || die "Node.js is required to build the frontend."
    command -v npm >/dev/null 2>&1 || die "npm is required to build the frontend."
    node - <<'JS' || die "Node.js 20.19+ or 22.12+ is required by Vite 8."
const [major, minor] = process.versions.node.split(".").map(Number);
const ok = (major === 20 && minor >= 19) || (major === 22 && minor >= 12) || major > 22;
process.exit(ok ? 0 : 1);
JS
fi

find_qbit_binary >/dev/null || die \
    "qbittorrent-nox was not found. Install it (sudo pacman -S qbittorrent-nox) or place the
binary at tools/qbittorrent-nox, then rerun setup."

if [ ! -f "$ENV_FILE" ]; then
    log "Creating .env with random credentials..."
    SETUP_TIMEZONE="$(timedatectl show -p Timezone --value 2>/dev/null || true)"
    [ -n "$SETUP_TIMEZONE" ] || SETUP_TIMEZONE="UTC"
    SEEDSTATION_SETUP_TIMEZONE="$SETUP_TIMEZONE" python3 - "$ROOT" <<'PY'
import os
import secrets
import shlex
import socket
import sys
from pathlib import Path

root = Path(sys.argv[1])
download_dir = root / "storage" / "downloads"
download_dir.mkdir(parents=True, exist_ok=True)
env_path = root / ".env"
hostname = socket.gethostname()

def q(value: str) -> str:
    return shlex.quote(value)

lines = [
    "# SeedStation local configuration. Generated by scripts/setup.sh.",
    "# Keep this file private (chmod 600). It holds the initial credentials.",
    f"SEEDSTATION_SECRET_KEY={q(secrets.token_urlsafe(48))}",
    "SEEDSTATION_DEBUG=false",
    "SEEDSTATION_PORT=8000",
    f"SEEDSTATION_ALLOWED_HOSTS={q(f'localhost,127.0.0.1,{hostname}')}",
    "SEEDSTATION_CSRF_TRUSTED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
    "SEEDSTATION_CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
    "SEEDSTATION_LAN_ONLY=true",
    "SEEDSTATION_SECURE_COOKIES=false",
    f"SEEDSTATION_DOWNLOAD_DIR={q(str(download_dir))}",
    "SEEDSTATION_EXTRA_DIRS=",
    f"SEEDSTATION_TIME_ZONE={q(os.environ.get('SEEDSTATION_SETUP_TIMEZONE', 'UTC'))}",
    "SEEDSTATION_ADMIN_USERNAME=admin",
    "SEEDSTATION_ADMIN_EMAIL=admin@seedstation.local",
    f"SEEDSTATION_ADMIN_PASSWORD={q(secrets.token_urlsafe(24))}",
    "SEEDSTATION_QBIT_HOST=127.0.0.1",
    "SEEDSTATION_QBIT_PORT=8081",
    "SEEDSTATION_QBIT_TORRENT_PORT=6881",
    "SEEDSTATION_QBIT_USERNAME=seedstation",
    f"SEEDSTATION_QBIT_PASSWORD={q(secrets.token_urlsafe(24))}",
    "SEEDSTATION_LOG_LEVEL=INFO",
    "",
]
env_path.write_text("\n".join(lines), encoding="utf-8")
env_path.chmod(0o600)
print(f"Created {env_path}")
PY
    ok "Generated .env (review SEEDSTATION_DOWNLOAD_DIR before adding large downloads)."
else
    ok "Using existing .env; leaving it unchanged."
fi

load_env
: "${SEEDSTATION_SECRET_KEY:?SEEDSTATION_SECRET_KEY is missing from .env}"
: "${SEEDSTATION_ADMIN_PASSWORD:?SEEDSTATION_ADMIN_PASSWORD is missing from .env}"
: "${SEEDSTATION_QBIT_PASSWORD:?SEEDSTATION_QBIT_PASSWORD is missing from .env}"

mkdir -p "$ROOT/storage/downloads" "$ROOT/backend/instance" "$RUN_DIR" "$QBIT_PROFILE"
[ -n "${SEEDSTATION_DOWNLOAD_DIR:-}" ] && mkdir -p "$SEEDSTATION_DOWNLOAD_DIR"
chmod 700 "$ROOT/backend/instance" "$QBIT_PROFILE" 2>/dev/null || true
chmod 600 "$ENV_FILE"

log "Installing Python dependencies..."
if [ ! -x "$VENV/bin/python" ]; then
    python3 -m venv "$VENV"
fi
if ! "$VENV/bin/python" -m pip --version >/dev/null 2>&1; then
    log "Bootstrapping pip in the virtual environment..."
    "$VENV/bin/python" -m ensurepip --upgrade
fi
"$VENV/bin/python" -m pip install --quiet --upgrade pip wheel
PIP_REQ="$ROOT/backend/requirements.txt"
[ "$WITH_DEV" -eq 1 ] && PIP_REQ="$ROOT/backend/requirements-dev.txt"
"$VENV/bin/python" -m pip install --quiet -r "$PIP_REQ"
ok "Python environment ready."

log "Preparing the isolated qBittorrent profile..."
"$VENV/bin/python" "$ROOT/scripts/generate_qbit_config.py" --root "$ROOT"

if [ "$SKIP_FRONTEND" -eq 0 ]; then
    log "Installing frontend dependencies..."
    if [ -f "$ROOT/frontend/package-lock.json" ]; then
        (cd "$ROOT/frontend" && npm ci --no-audit --no-fund)
    else
        (cd "$ROOT/frontend" && npm install --no-audit --no-fund)
    fi
    log "Building the frontend..."
    (cd "$ROOT/frontend" && npm run build)
    ok "Frontend build ready."
else
    warn "Skipping frontend install/build; serving the existing frontend/dist."
    [ -f "$ROOT/frontend/dist/index.html" ] || die "frontend/dist/index.html is missing; rerun without --skip-frontend."
fi

log "Applying database migrations..."
(cd "$ROOT/backend" && "$VENV/bin/python" manage.py migrate --noinput)
log "Collecting Django admin static files..."
(cd "$ROOT/backend" && "$VENV/bin/python" manage.py collectstatic --noinput >/dev/null)
log "Ensuring the administrator account exists..."
(cd "$ROOT/backend" && "$VENV/bin/python" manage.py bootstrap_admin)

ok "Setup complete."
printf '\n%sNext:%s\n' "$C_BOLD" "$C_RESET"
printf '  ./scripts/start.sh\n'
printf '  open http://127.0.0.1:%s\n' "${SEEDSTATION_PORT:-8000}"
printf '\nThe administrator username is %s. For a fresh install, the initial password\n' "${SEEDSTATION_ADMIN_USERNAME:-admin}"
printf 'is in .env; if you changed it in Settings, use that password instead.\n'
printf 'The qBittorrent WebUI is loopback-only and managed by SeedStation.\n'

if [ "$START_AFTER" -eq 1 ]; then
    exec "$SCRIPT_DIR/start.sh"
fi
