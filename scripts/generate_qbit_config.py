#!/usr/bin/env python3
"""Generate an isolated qBittorrent profile for SeedStation.

qBittorrent stores WebUI passwords as PBKDF2-HMAC-SHA512 (100,000 iterations)
inside an @ByteArray value. Generating the profile up front keeps the WebUI on
loopback with a known credential and avoids parsing qBittorrent's temporary
first-run password from a log.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import os
import secrets
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PBKDF2_ITERATIONS = 100_000
PBKDF2_DKLEN = 64


def read_dotenv(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].lstrip()
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key] = value
    return values


def setting(dotenv: dict[str, str], key: str, default: str = "") -> str:
    return os.environ.get(key, dotenv.get(key, default))


def password_hash(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac(
        "sha512", password.encode("utf-8"), salt, PBKDF2_ITERATIONS, dklen=PBKDF2_DKLEN
    )
    return (
        f"@ByteArray({base64.b64encode(salt).decode('ascii')}:"
        f"{base64.b64encode(digest).decode('ascii')})"
    )


def clean(value: str, label: str) -> str:
    if "\n" in value or "\r" in value or "\x00" in value:
        raise SystemExit(f"{label} contains invalid characters.")
    return value.replace("\\", "\\\\")


def build_config(dotenv: dict[str, str]) -> tuple[str, dict[str, str]]:
    download_dir = Path(
        setting(dotenv, "SEEDSTATION_DOWNLOAD_DIR", str(PROJECT_ROOT / "storage" / "downloads"))
    ).expanduser()
    if not download_dir.is_absolute():
        raise SystemExit("SEEDSTATION_DOWNLOAD_DIR must be an absolute path.")
    download_dir.mkdir(parents=True, exist_ok=True)

    username = clean(setting(dotenv, "SEEDSTATION_QBIT_USERNAME", "seedstation"), "qBittorrent username")
    password = setting(dotenv, "SEEDSTATION_QBIT_PASSWORD")
    if not username:
        raise SystemExit("SEEDSTATION_QBIT_USERNAME must not be empty.")
    if not password:
        raise SystemExit(
            "SEEDSTATION_QBIT_PASSWORD is empty. Set a strong password in .env before generating the profile."
        )
    webui_port = clean(setting(dotenv, "SEEDSTATION_QBIT_PORT", "8081"), "qBittorrent WebUI port")
    torrent_port = clean(
        setting(dotenv, "SEEDSTATION_QBIT_TORRENT_PORT", "6881"), "qBittorrent torrent port"
    )
    save_path = clean(str(download_dir.resolve()), "Download directory")

    config = f"""\
# Generated by SeedStation. Keep this file private.
[BitTorrent]
Session\\DefaultSavePath={save_path}
Session\\TempPath={save_path}
Session\\TempPathEnabled=false
Session\\GlobalDLSpeedLimit=0
Session\\GlobalUPSpeedLimit=0
Session\\Interface=
Session\\InterfaceName=
Session\\DHTEnabled=true
Session\\LSDEnabled=true
Session\\MaxActiveDownloads=3
Session\\MaxActiveTorrents=6
Session\\NATPMPEnabled=false
Session\\Port={torrent_port}
Session\\QueueingSystemEnabled=true
Session\\SSL\\Port=0
Session\\StartPaused=false
Session\\UPnPEnabled=false

[LegalNotice]
Accepted=true

[Meta]
MigrationVersion=12

[Network]
PortForwardingEnabled=false

[WebUI]
Address=127.0.0.1
AlternativeUIEnabled=false
CSRFProtection=true
ClickjackingProtection=true
Enabled=true
HostHeaderValidation=true
LocalHostAuth=true
MaxAuthenticationFailCount=5
Password_PBKDF2="{password_hash(password)}"
Port={webui_port}
Username={username}
"""
    meta = {
        "download_dir": str(download_dir.resolve()),
        "username": username,
        "webui_port": webui_port,
        "torrent_port": torrent_port,
    }
    return config, meta


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=PROJECT_ROOT,
        help="SeedStation project root (defaults to the parent of this script).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing qBittorrent.conf. Stop the engine first.",
    )
    args = parser.parse_args()

    root = args.root.resolve()
    env_path = root / ".env"
    config_path = root / ".qbittorrent" / "qBittorrent" / "config" / "qBittorrent.conf"

    if config_path.exists() and not args.force:
        print(f"qBittorrent profile already exists: {config_path}")
        return 0

    dotenv = read_dotenv(env_path)
    config, meta = build_config(dotenv)

    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.parent.chmod(0o700)
    config_path.write_text(config, encoding="utf-8")
    config_path.chmod(0o600)

    print(f"Wrote qBittorrent profile: {config_path}")
    print(f"  WebUI: http://127.0.0.1:{meta['webui_port']} (loopback only)")
    print(f"  Torrent port: {meta['torrent_port']}")
    print(f"  Download path: {meta['download_dir']}")
    print(f"  WebUI user: {meta['username']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
